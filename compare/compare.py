"""Build the NumPy vs GPU comparison from the result JSON files.

    python compare/compare.py
    -> compare/README.md       tables
    -> compare/figures/*.png    throughput and batch-size charts

Reads results/part2_numpy.json (Part II, B's run), results/part3_torch.json
(Part III main run) and results/part3_runs/*.json (Part III experiments, from
part3_torch_cnn/run_experiments.py). Missing runs are skipped.
"""
from pathlib import Path
import json
import statistics as st

ROOT = Path(__file__).resolve().parents[1]
OUT = ROOT / "compare"
RUNS = ROOT / "results" / "part3_runs"


def load(path):
    p = ROOT / path if not Path(path).is_absolute() else Path(path)
    return json.loads(p.read_text(encoding="utf-8")) if p.exists() else None


def run(name):
    return load(RUNS / f"{name}.json")


def hardware(r):
    env = r.get("environment", {})
    if r.get("device") == "cuda":
        return env.get("gpu", "GPU")
    return env.get("cpu", "CPU")


def net(r):
    if r.get("part") == "part2_numpy":
        return "Part II network (NumPy)"
    s = r["settings"]
    if s["model"] == "numpy_equiv":
        return "Part II network"
    return "CatDogCNN, " + ("ReLU + MSE (handout)" if s["head"] == "relu_mse" else "sigmoid + BCE")


def training(r):
    s = r["settings"]
    if r.get("part") == "part2_numpy" or s.get("train_mode") == "online":
        return "online SGD, 1 image per update"
    return f"{s['optimizer']}, batch {s['optimizer_batch_size']}"


def impl(r):
    if r.get("part") == "part2_numpy":
        return "NumPy"
    return "PyTorch " + ("GPU" if r["device"] == "cuda" else r["device"].upper())


def dead(r):
    return r["metrics"].get("zero_output_fraction", 0) == 1.0 or min(map(sum, zip(*r["metrics"]["confusion_matrix"]))) == 0


def fmt(x, nd=3):
    return "–" if x is None else f"{x:,.{nd}f}"


def table(headers, rows):
    lines = ["| " + " | ".join(headers) + " |", "|" + "|".join("---" for _ in headers) + "|"]
    lines += ["| " + " | ".join(str(c) for c in row) + " |" for row in rows]
    return "\n".join(lines)


def perf_row(r, base=None, label=None):
    t = r["timing"]
    row = [label or impl(r), net(r), training(r), hardware(r),
           fmt(r["train_seconds"]), fmt(t["train_images_per_second"], 0),
           fmt(r["test_seconds"], 4), fmt(t["test_images_per_second"], 0),
           f"{100 * r['accuracy']:.1f}%" + (" (one class only)" if dead(r) else "")]
    if base is not None:
        row += [f"{base['train_seconds'] / r['train_seconds']:.2f}×",
                f"{base['test_seconds'] / r['test_seconds']:.2f}×"]
    return row


PERF_HEAD = ["Implementation", "Network", "Training", "Hardware", "Train s (10 epochs)",
             "Train images/s", "Test s", "Test images/s", "Test accuracy"]


def main():
    md = ["# Part II (NumPy) vs Part III (PyTorch on the GPU)",
          "",
          "Generated by `compare/compare.py` from the result JSON files. Train and test times are",
          "computation only (image loading and decoding excluded), as defined in each JSON's",
          "`timing.definition`. Test images are the unseen `test/` split. Speed-ups are",
          "ratios of times on the same machine. Each row is one run (1 warm-up, then 10 epochs and",
          "one pass over the test set).",
          "",
          "GPU training is not bit-for-bit reproducible: some cuDNN kernels add in a different order",
          "from run to run, so the same configuration and seed can differ by a percentage point or",
          "two in accuracy (for example sigmoid + BCE, batch 64, seed 542 appears in sections 3 and 6",
          "as two separate runs).",
          ""]
    figures = {}

    # 1. The comparison the handout asks for.
    rows = []
    for r in (load("results/part2_numpy.json"), run("numpy_part2_code"),
              load("results/part3_torch.json"), run("catdog_bce_gpu_seed542")):
        if r:
            rows.append(perf_row(r))
    if rows:
        md += ["## 1. NumPy (Part II) vs GPU (Part III)", "",
               table(PERF_HEAD, rows), "",
               "The two parts use different networks: Part II trains only the FC layer behind one fixed",
               "random filter, Part III trains two convolution and two FC layers. Section 2 compares the",
               "implementations on the same network.", ""]

    # 2. Same network, same algorithm.
    base = run("numpy_part2_code")
    same = [run(n) for n in ("numpy_part2_code", "numpy_equiv_online_cpu", "numpy_equiv_online_gpu",
                             "numpy_equiv_batch64_cpu", "numpy_equiv_batch64_gpu")]
    same = [r for r in same if r]
    if base and len(same) > 1:
        md += ["## 2. Same network: Part II's network in NumPy and in PyTorch", "",
               table(PERF_HEAD + ["Train speed-up vs NumPy", "Test speed-up vs NumPy"],
                     [perf_row(r, base) for r in same]), "",
               "The online rows run Part II's algorithm step for step (same initial weights, same",
               "shuffle order; `part3_torch_cnn/test_part3.py` checks that the weights match NumPy's).",
               "The batch-64 rows change the algorithm to mini-batch SGD to show what batching does.", ""]
        figures["same_network"] = [(f"{impl(r)}\n{training(r).split(',')[0]}", r["timing"]["train_images_per_second"]) for r in same]

    # 3. Output head across seeds.
    head_rows, summary = [], {}
    for head in ("relu_mse", "bce"):
        accs = []
        for name in sorted(p.stem for p in RUNS.glob(f"catdog_{head}_gpu_seed*.json")):
            r = run(name)
            accs.append((r["seed"], r["accuracy"], dead(r)))
        if accs:
            summary[head] = accs
            vals = [a for _, a, _ in accs]
            head_rows.append(["ReLU + MSE (handout)" if head == "relu_mse" else "sigmoid + BCE",
                              ", ".join(f"{s}: {100 * a:.1f}%" for s, a, _ in accs),
                              f"{sum(d for *_, d in accs)} of {len(accs)}",
                              f"{100 * st.mean(vals):.1f}% ± {100 * st.stdev(vals):.1f}" if len(vals) > 1 else "–"])
    if head_rows:
        md += ["## 3. Output layer: the handout's ReLU + MSE vs sigmoid + BCE (CatDogCNN, GPU)", "",
               table(["Output and loss", "Test accuracy by seed", "Runs that predict one class only",
                      "Mean ± std"], head_rows), "",
               "With a ReLU on the single output, a network whose outputs all fall below zero gets zero",
               "gradient and stops learning: it then predicts one class for every image. A logit output",
               "with BCEWithLogitsLoss always has a gradient.", ""]

    # 4. CPU vs GPU on CatDogCNN.
    pairs = [("data_small", run("catdog_bce_cpu_seed542"), run("catdog_bce_gpu_seed542")),
             ("data (full)", run("catdog_bce_cpu_full"), run("catdog_bce_gpu_full"))]
    rows = []
    for ds, c, g in pairs:
        if c and g:
            rows.append([ds, f"{c['num_train']:,} / {c['num_test']:,}", hardware(c), hardware(g),
                         fmt(c["train_seconds"]), fmt(g["train_seconds"]),
                         f"{c['train_seconds'] / g['train_seconds']:.1f}×",
                         f"{c['test_seconds'] / g['test_seconds']:.1f}×",
                         f"{100 * c['accuracy']:.1f}% / {100 * g['accuracy']:.1f}%"])
    if rows:
        md += ["## 4. CatDogCNN on the CPU vs the GPU (PyTorch, sigmoid + BCE)", "",
               table(["Data", "Train / test images", "CPU", "GPU", "CPU train s", "GPU train s",
                      "Train speed-up", "Test speed-up", "Accuracy CPU / GPU"], rows), ""]

    # 5. Input pipeline.
    pre, w0, w4 = run("catdog_bce_gpu_seed542"), run("catdog_bce_gpu_disk_w0"), run("catdog_bce_gpu_disk_w4")
    rows = []
    for r, how in ((pre, "decoded once, tensors kept in GPU memory"),
                   (w0, "ImageFolder + DataLoader every epoch, 0 workers"),
                   (w4, "ImageFolder + DataLoader every epoch, 4 workers")):
        if r:
            rows.append([how, fmt(r["train_seconds"]), fmt(r["timing"]["train_images_per_second"], 0),
                         f"{100 * r['accuracy']:.1f}%"])
    if len(rows) > 1:
        md += ["## 5. Input pipeline (CatDogCNN, sigmoid + BCE, GPU)", "",
               table(["Images reach the GPU by", "Train s (10 epochs)", "Train images/s", "Test accuracy"], rows), "",
               "For the disk rows the training time includes decoding and resizing every image on the CPU.", ""]

    # 6. Batch size.
    bs = []
    for b in (16, 64, 256, 1024):
        r = run(f"catdog_bce_gpu_bs{b}")
        if r:
            bs.append((b, r))
    if bs:
        md += ["## 6. Batch size (CatDogCNN, sigmoid + BCE, GPU)", "",
               table(["Batch size", "Train s (10 epochs)", "Train images/s", "Test accuracy"],
                     [[b, fmt(r["train_seconds"]), fmt(r["timing"]["train_images_per_second"], 0),
                       f"{100 * r['accuracy']:.1f}%"] for b, r in bs]), "",
               "Larger batches give the GPU more parallel work per kernel launch, but also fewer weight",
               "updates per epoch, which changes accuracy after a fixed number of epochs.", ""]
        figures["batch"] = [(b, r["timing"]["train_images_per_second"]) for b, r in bs]

    # Environment of the Part III runs.
    main_run = load("results/part3_torch.json")
    if main_run:
        env = main_run["environment"]
        md += ["## Environment (Part III runs)", "",
               table(["Item", "Value"], [[k, v] for k, v in env.items()]), ""]

    OUT.mkdir(exist_ok=True)
    try:
        import matplotlib
        matplotlib.use("Agg")
        import matplotlib.pyplot as plt
        (OUT / "figures").mkdir(exist_ok=True)
        if "same_network" in figures:
            names, vals = zip(*figures["same_network"])
            fig, ax = plt.subplots(figsize=(8, 4))
            ax.bar(names, vals, color="#4C72B0")
            ax.set_yscale("log")
            ax.set_ylabel("training images / s (log scale)")
            ax.set_title("Part II's network: NumPy vs PyTorch CPU vs PyTorch GPU")
            for i, v in enumerate(vals):
                ax.text(i, v, f"{v:,.0f}", ha="center", va="bottom", fontsize=8)
            fig.tight_layout()
            fig.savefig(OUT / "figures" / "same_network_throughput.png", dpi=150)
            md += ["![Training throughput on Part II's network](figures/same_network_throughput.png)", ""]
        if "batch" in figures:
            b, v = zip(*figures["batch"])
            fig, ax = plt.subplots(figsize=(6, 4))
            ax.plot(b, v, marker="o")
            ax.set_xscale("log", base=2)
            ax.set_xlabel("batch size")
            ax.set_ylabel("training images / s")
            ax.set_title("CatDogCNN on the GPU: throughput vs batch size")
            fig.tight_layout()
            fig.savefig(OUT / "figures" / "batch_size.png", dpi=150)
            md += ["![Throughput against batch size](figures/batch_size.png)", ""]
    except ImportError:
        md += ["(matplotlib not installed: figures skipped)", ""]

    (OUT / "README.md").write_text("\n".join(md), encoding="utf-8")
    print(f"wrote {OUT / 'README.md'}")


if __name__ == "__main__":
    main()
